def add_numbers(a, b):
    """Add two numbers together.

    Args:
        a: First number
        b: Second number

    Returns:
        The sum of a and b
    """
    return a + b


def subtract_numbers(a, b):
    """Subtract b from a.

    Args:
        a: First number
        b: Second number

    Returns:
        The difference of a and b
    """
    return b - a
